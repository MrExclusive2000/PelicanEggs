    private const RESPAWN_KINDS = ['Random' => 'at a random spot', 'Sector' => 'in a chosen sector', 'Shelter' => 'at their shelter or bed', 'Squad' => 'next to a squadmate'];

    /** An explanation for the key, or null when there is nothing better than its name. */
    public static function describe(string $key, string $value = ''): ?string
    {
        $name = preg_replace('/^scum\./i', '', $key) ?? $key;
        if (isset(self::KEYS[$name])) {
            return self::KEYS[$name];
        }

        $words = fn (string $text) => strtolower(SettingLabel::fromKey($text));

        $patterns = [
            '/^(\w+?)PrevalenceMultiplier$/' => fn ($m) => 'How common ' . $words($m[1]) . 's are compared to other animals. 1 = normal, 0 = none.',
            '/^(Bear|Boar|Chicken|Deer|Donkey|Goat|Horse|Rabbit|Wolf)MaxHealthMultiplier$/' => fn ($m) => 'Health of ' . strtolower($m[1]) . 's. 1 = normal.',
            '/^(\w+?)SkillMultiplier$/' => fn ($m) => 'How fast players learn ' . $words($m[1]) . '. 1 = normal, 2 = twice as fast.',
            '/^(\w+?)MaxFunctionalAmount$/' => fn ($m) => 'How many ' . $words($m[1]) . 's spawn ready to use; the rest spawn needing repair.',
            '/^(\w+?)MinPurchasedAmount$/' => fn ($m) => 'How many ' . $words($m[1]) . 's are kept available to buy from traders.',
            '/^(\w+?)MaxAmount$/' => fn ($m) => 'Most ' . $words($m[1]) . 's on the map at once (found and bought).',
            '/^(Random|Sector|Shelter|Squad)RespawnPrice$/' => fn ($m) => 'Cost to respawn ' . self::RESPAWN_KINDS[$m[1]] . '. A plain number is cash; ending in "g" is gold.',
            '/^(Random|Sector|Shelter|Squad)RespawnInitialTime$/' => fn ($m) => 'Seconds after death before respawning ' . self::RESPAWN_KINDS[$m[1]] . ' is available.',
            '/^(Random|Sector|Shelter|Squad)RespawnCooldown$/' => fn ($m) => 'Seconds before respawning ' . self::RESPAWN_KINDS[$m[1]] . ' can be used again.',
            '/^(Random|Sector|Shelter|Squad)CooldownResetMultiplier$/' => fn ($m) => 'How quickly the cooldown for respawning ' . self::RESPAWN_KINDS[$m[1]] . ' wears off.',
            '/^(Random|Sector|Shelter)PricePerSquadmateModifier$/' => fn ($m) => 'Extra respawn cost ' . self::RESPAWN_KINDS[$m[1]] . ' for each squad member.',
            '/^ShelterRespawnPriceOutsideFlagArea$/' => fn () => 'Cost to respawn at a shelter outside a flag area (g = gold).',
            '/^(Water|Gasoline|Propane)PricePerUnitMultiplier$/' => fn ($m) => 'Price of ' . strtolower($m[1]) . ' at pumps and taps. 1 = normal.',
            '/^(Water|Gasoline|Propane)Periodic(\w+)Multiplier$/' => fn ($m) => ucfirst(strtolower($m[1])) . ' stations refilling over time: ' . $words($m[2]) . '. 1 = normal.',
            '/^(Water|Gasoline|Propane)Proximity(\w+)Multiplier$/' => fn ($m) => ucfirst(strtolower($m[1])) . ' stations refilling when players are near: ' . $words($m[2]) . '. 1 = normal.',
            '/^(\w+?)MaxAmountPerFlagArea$/' => fn ($m) => 'Most ' . $words($m[1]) . 's in one flag area. -1 = no limit.',
            '/^(\w+?)StartDecayingIfFlagAreaHasMoreThan$/' => fn ($m) => $words($m[1]) . 's start to decay when a flag area has more than this. -1 = never.',
            '/^TurretsAttack(\w+)$/' => fn ($m) => 'Base turrets shoot at ' . $words($m[1]) . '.',
            '/^(\w+?)DamageMultiplier$/' => fn ($m) => 'Damage dealt by ' . $words($m[1]) . '. 1 = normal.',
            '/^(\w+?)HealthMultiplier$/' => fn ($m) => 'Health of ' . $words($m[1]) . 's. 1 = normal.',
            '/^Encounter(\w+)$/' => fn ($m) => 'AI spawning (puppets, NPCs): ' . $words($m[1]) . '. 1 = normal. ' . self::MINUS_ONE,
            '/^(\w+?)WorldEncounterSpawnWeightMultiplier$/' => fn ($m) => 'How often ' . $words($m[1]) . ' encounters happen. 1 = normal.',
            '/^AbandonedBunker(\w+)$/' => fn ($m) => 'Abandoned bunkers: ' . $words($m[1]) . '. ' . self::MINUS_ONE,
        ];
        foreach ($patterns as $pattern => $explain) {
            if (preg_match($pattern, $name, $match)) {
                return ucfirst($explain($match));
            }
        }

        return null;
    }
